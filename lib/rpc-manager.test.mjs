test("crossing the Chat-only boundary persists and rebuilds the wrapper", async () => {
  const source = await readFile(new URL("./rpc-manager.ts", import.meta.url), "utf8");
  const switchSource = source.slice(
    source.indexOf("export function setRpcSessionTools"),
    source.indexOf("export function getRunningRpcSessionIds"),
  );

  assert.match(switchSource, /!hasCurrentResourcePolicy\s*\|\| existing\.isChatOnly\(\) !== \(toolNames\.length === 0\)/);
  // The pin is written by whoever owns the session file: the engine's single
  // writer (a live CLI child, or its manager) or, once the child exited, the
  // host. `toolPinRestartPhase` is the only place that decides which.
  assert.match(switchSource, /const pinPhase = toolPinRestartPhase\(existing\.inner\)/);
  assert.match(switchSource, /if \(pinPhase !== "host-after-exit"\) \{\s*\/\/[\s\S]*await existing\.persistToolSelection\(toolNames\)/);
  assert.match(switchSource, /await existing\.persistToolSelection\(toolNames\);\s*invalidateSessionListCache\(\);\s*\}\s*\n\s*if \(persistedFile\)/);
  // An in-process engine still appends through its own session manager.
  assert.match(source, /appendSessionToolSelection\(this\.inner\.sessionManager, toolNames\)/);
  assert.match(switchSource, /await existing\.shutdown\(\)/);
  assert.match(switchSource, /__recreate__\$\{randomUUID\(\)\}/);
  assert.match(switchSource, /sessionId: started\.realSessionId/);
});

